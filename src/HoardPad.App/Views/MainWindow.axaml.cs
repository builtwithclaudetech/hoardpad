    /// <summary>Resolves the clicked context-menu item's <c>Tag</c> back to its <see cref="DocumentTab"/>.</summary>
    private static DocumentTab? MenuItemTab(object? sender) =>
        (sender as MenuItem)?.Tag as DocumentTab;

    private Task CopyToClipboardAsync(string text)
    {
        Avalonia.Input.Platform.IClipboard? clipboard = TopLevel.GetTopLevel(this)?.Clipboard;
        return clipboard?.SetTextAsync(text) ?? Task.CompletedTask;
    }

    /// <summary>
    /// Resolve the target tab index for a horizontal drop — pure function testable without a live ItemsControl.
    /// <paramref name="widths"/> is the sequence of realized tab widths; <paramref name="spacing"/> is the gap
    /// between consecutive chips (the StackPanel's Spacing); <paramref name="x"/> is the drop X coordinate
    /// relative to the strip's left edge. Returns the 0-based index of the slot the pointer is closest to;
    /// returns <paramref name="widths"/>.<see cref="IReadOnlyList{T}.Count"/> when past the last tab (the
    /// "append at end" sentinel — <see cref="MainWindowViewModel.MoveTab"/> clamps it to <c>Count-1</c>).
    /// </summary>
    internal static int ComputeDropIndex(IReadOnlyList<double> widths, double spacing, double x)
    {
        int count = widths.Count;
        if (count == 0)
            return 0;

        double cumulative = 0;
        for (int i = 0; i < count; i++)
        {
            double w = widths[i];
            if (x < cumulative + w / 2)
                return i; // drop before this tab.
            cumulative += w + (i < count - 1 ? spacing : 0); // spacing only between chips, not after last.
        }

        return count; // past the last tab → "append at end" sentinel; MoveTab clamps to Count-1.
    }

    /// <summary>
    /// Window-level KeyDown handler: Esc closes the find/replace panel when visible (BUG-2).
    /// Only fires when the event was not already handled by a child (e.g., the panel's own Esc handler).
    /// This ensures Esc dismisses the panel even when focus is outside it (e.g., in the editor below).
    /// </summary>
    private void OnWindowKeyDown(object? sender, KeyEventArgs e)
    {
        if (e.Handled)
            return;
        if (e.Key != Key.Escape)
            return;
        if (_findReplace is not { IsVisible: true })
            return;

        _findReplace.IsVisible = false;
        e.Handled = true;
    }

