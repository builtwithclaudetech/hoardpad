    /// <summary>The DataObject format key for the dragged tab id (M8.1 tab-strip reorder). The tab's
    /// TabId travels (not the object) so the drop resolves back to the live instance in the Tabs set.</summary>
    private const string DragTabIdFormat = "HoardPad.TabId";

    /// <summary>The spacing between tab chips in the StackPanel (must match the ItemsPanelTemplate Spacing="4").</summary>
    private const double TabStripSpacing = 4.0;

    private FindReplaceViewModel? _findReplace;

    /// <summary>Track the previous shell VM so we can null its view-bound delegates on re-wire (leak guard).</summary>
    private MainWindowViewModel? _previousShell;

    /// <summary>The distance (in window-relative pixels) a pointer must travel from its press point before a
    /// tab-chip press is promoted to an OS drag (QA3-14 / QA3-3 fix — see <see cref="OnTabPointerPressed"/>).</summary>
    private const double DragStartThresholdPixels = 5.0;

    /// <summary>The tab whose chip currently has a pending pointer press — pending either a drag (if the
    /// pointer crosses <see cref="DragStartThresholdPixels"/> before release) or a plain click (activated
    /// directly by <see cref="OnWindowPointerReleased"/> — see its doc comment for why activation is no
    /// longer wired through Avalonia's built-in Tapped gesture). Null when no press is pending.</summary>
    private DocumentTab? _dragCandidateTab;

    /// <summary>The pointer that owns <see cref="_dragCandidateTab"/> — guards against a second pointer
    /// (e.g. touch) interfering with an in-flight candidate.</summary>
    private IPointer? _dragCandidatePointer;

    /// <summary>The window-relative point of the original PointerPressed, for threshold comparison.</summary>
    private Point _dragCandidateStartPoint;

    /// <summary>The AI panel column's last known Pixel width (QA5-B2), remembered across a hide/show
    /// cycle so re-showing the panel restores the user's chosen size instead of falling back to the
    /// default. Null only until the panel has been shown at least once. NOT a precise "was this a real
    /// drag" flag (N4): it captures whatever Pixel width the column last held when hidden, which may be a
    /// just-assigned <see cref="AiPanelDefaultColumnWidth"/> from a prior show rather than a genuine
    /// GridSplitter drag — harmless today because the two values coincide, but worth knowing if the
    /// default ever becomes configurable. See <see cref="SyncAiPanelColumnWidth"/> for the full mechanism.
    /// </summary>
    private double? _aiPanelLastWidth;

    public MainWindow()
    {
        InitializeComponent();   // source-generated by the Avalonia build task
        SetBrandIcon();
        DataContextChanged += OnDataContextChanged;

        // M8.1 (cut-tail #1): tab-strip drag-reorder — mirror the ChecklistView DragDrop wiring (bubbling
        // Drop/DragOver handlers). The per-tab PointerPressed only records a drag CANDIDATE
        // (OnTabPointerPressed); the OS drag loop itself starts later, from these window-level handlers,
        // only once the pointer crosses DragStartThresholdPixels (QA3-14 / QA3-3 — see the doc comment on
        // OnTabPointerPressed for why the drag can no longer start unconditionally on press).
        AddHandler(DragDrop.DropEvent, OnTabDrop, RoutingStrategies.Bubble);
        AddHandler(DragDrop.DragOverEvent, OnTabDragOver, RoutingStrategies.Bubble);
        AddHandler(InputElement.PointerMovedEvent, OnWindowPointerMoved, RoutingStrategies.Bubble);
        AddHandler(InputElement.PointerReleasedEvent, OnWindowPointerReleased, RoutingStrategies.Bubble);
        AddHandler(InputElement.PointerCaptureLostEvent, OnWindowPointerCaptureLost, RoutingStrategies.Bubble);

        // BUG-2: Window-level Esc handler closes the find/replace panel regardless of focus.
        // The panel's own handler fires when focus is inside it; this handler catches Esc when
        // focus is in the editor or any other sibling (the panel's handler never fires in that case).
        // For this to ever run with focus in the editor, EditorView.axaml.cs must also uninstall
        // AvaloniaEdit's auto-installed SearchPanel — its built-in CommandBindings-based handler
        // otherwise swallows Escape (SearchCommands.CloseSearchPanel's default gesture) at the TextArea
        // level, unconditionally, even though that stock panel is never shown (see EditorView.axaml.cs).
        KeyDown += OnWindowKeyDown;
    }

    /// <summary>
    /// Wire the BUG-3 close-confirm delegate + M6.7 find/replace panel once the composition root has
    /// attached the shell VM.
    /// </summary>
    private void OnDataContextChanged(object? sender, System.EventArgs e)
    {
        // Null the previous shell's view-bound delegates to close the lambda closure (leak guard).
        if (_previousShell is { } prev)
        {
            prev.ConfirmCloseTab = null;
            prev.ShowHelpHandler = null;
            prev.IsNonEditorTextInputFocused = null;
            prev.PropertyChanged -= OnShellPropertyChanged;
            // QA5-B2 hostile-review W3: the remembered drag width belongs to the OLD shell's session, not
            // the new one — a reassignment (currently unreachable; only one DataContext assignment exists
            // in App.axaml.cs today, but the SyncAiPanelColumnWidth doc comment already anticipates a
            // future session-restore path) must not leak it forward.
            _aiPanelLastWidth = null;
        }

        if (DataContext is not MainWindowViewModel shell)
            return;

        _previousShell = shell;

        // Wire the MODAL unsaved-changes confirm prompt (BUG-3): a real ShowDialog(owner) over this window.
        // `this` is MainWindow (a Window), so it is the owner directly — no GetVisualRoot lookup needed.
        shell.ConfirmCloseTab = tab =>
            ConfirmCloseDialog.ShowAsync(this, tab.DisplayName);

        // Wire the Help ▸ About MODAL dialog (QA2-14) — same owner-window rationale as ConfirmCloseTab.
        shell.ShowHelpHandler = () => AboutDialog.ShowAsync(this);

        // QA4-14/W1: only the View can query Avalonia's live FocusManager. A TextArea is never "a non-editor
        // text input" (it's the document editor itself); a focused TextBox anywhere ELSE in the shell
        // (Find/Replace, checklist rename/add-item, Settings, the AI panel prompt, …) is.
        shell.IsNonEditorTextInputFocused = () =>
            TopLevel.GetTopLevel(this)?.FocusManager?.GetFocusedElement() is Visual focused
            && (focused is TextBox || focused.GetSelfAndVisualAncestors().OfType<TextBox>().Any());

        // BUG-2: Subscribe to the shell's PropertyChanged so we catch AttachFindReplace being called
        // after DataContext is set (App.axaml.cs assigns DataContext before calling AttachFindReplace,
        // so FindReplace is null during the initial OnDataContextChanged call).
        shell.PropertyChanged += OnShellPropertyChanged;

        // QA5-B2: sync the AI panel column ONCE against whatever IsAiPanelVisible already is at attach
        // time — a PropertyChanged subscription only observes future TRANSITIONS, so a shell constructed
        // with IsAiPanelVisible already true (e.g. a future session-restore path, or a test building the
        // window pre-visible) would otherwise never run SyncAiPanelColumnWidth and fall through to the
        // "Auto" column's own natural content measurement, which is NOT 300 — see SyncAiPanelColumnWidth's
        // doc comment for why the panel's real content needs this explicit sync.
        SyncAiPanelColumnWidth(shell.IsAiPanelVisible);

        // Wire immediately if FindReplace is already non-null (e.g. on a DataContext reassignment
        // where AttachFindReplace was called before the new DataContext was set).
        if (shell.FindReplace is { } findReplace)
            WireFindReplace(findReplace);
    }

    private void OnShellPropertyChanged(object? sender, PropertyChangedEventArgs e)
    {
        // QA4-13 (hostile-review CRITICAL fix): GridSplitter converts the folder column's "Auto"
        // GridLength to a concrete Pixel value on drag and never reverts it on its own — see
        // ResetFolderColumnWidth's doc comment for the full rationale.
        if (e.PropertyName == nameof(MainWindowViewModel.IsFolderTreeVisible)
            && sender is MainWindowViewModel { IsFolderTreeVisible: false })
        {
            ResetFolderColumnWidth();
        }

        // QA5-B2: mirror the same "Auto column, hidden child measures 0" fix for the AI panel's own
        // column 4 — see SyncAiPanelColumnWidth's doc comment for why this one additionally remembers a
        // dragged width across the hide/show cycle, which ResetFolderColumnWidth deliberately does not.
        if (e.PropertyName == nameof(MainWindowViewModel.IsAiPanelVisible)
            && sender is MainWindowViewModel { IsAiPanelVisible: bool isAiPanelVisible })
        {
            SyncAiPanelColumnWidth(isAiPanelVisible);
        }

        if (e.PropertyName != nameof(MainWindowViewModel.FindReplace))
            return;
        if (sender is not MainWindowViewModel shell)
            return;
        if (shell.FindReplace is not { } findReplace)
            return;

        WireFindReplace(findReplace);
    }

    /// <summary>
    /// QA4-13 (hostile-review CRITICAL fix): Avalonia's <see cref="GridSplitter"/> converts the folder
    /// column's "Auto" <see cref="GridLength"/> to a concrete Pixel value the moment it is dragged, and
    /// nothing reverts it afterward — so the ordinary flow "open a folder → drag the splitter to, say,
    /// 260px → hide the tree to focus the editor" would otherwise leave 260px of PERMANENT dead space
    /// reserved even with the panel hidden (the exact regression the "Auto" column was chosen to prevent
    /// in the first place). Reset the column back to <see cref="GridLength.Auto"/> every time
    /// <c>IsFolderTreeVisible</c> transitions to false so it collapses to 0 again, matching a bare launch.
    /// Re-showing the tree currently reverts to the folder Border's static <c>Width="200"</c> default
    /// rather than remembering the user's last dragged size — a deliberate, reviewed simplification (not
    /// persisted); restoring the last dragged width on re-show is a reasonable follow-up, not required here.
    /// </summary>
    private void ResetFolderColumnWidth()
    {
        if (this.FindControl<GridSplitter>("FolderPanelSplitter")?.Parent is not Grid grid)
            return;
        grid.ColumnDefinitions[0].Width = GridLength.Auto;
    }

    /// <summary>The AI panel column's default width (QA5-B2) — matches the pre-fix fixed pixel column
    /// ("300") this replaces, and is what a shown panel falls back to before the user has ever dragged
    /// <c>AiPanelSplitter</c>.</summary>
    private const double AiPanelDefaultColumnWidth = 300;

    /// <summary>
    /// QA5-B2 (dogfooding): the AI panel's own column 4 used to be a fixed pixel width ("300"),
    /// so it reserved that space even while <c>AiPanel</c> was hidden — the "always reserved when
    /// hidden" quirk <see cref="ResetFolderColumnWidth"/>'s doc comment explicitly deferred (QA4-13
    /// scoped it out). This closes it by mirroring the same Auto-column fix — column 4 is now "Auto" in
    /// MainWindow.axaml, so an Auto column with a hidden child measures to 0 exactly like column 0.
    ///
    /// Unlike <see cref="ResetFolderColumnWidth"/>, this one also remembers a dragged width across the
    /// hide/show cycle — QA5-B2's brief requires re-showing the panel to restore the user's PRIOR
    /// width, not the default. A completed GridSplitter drag leaves <c>grid.ColumnDefinitions[4].Width</c>
    /// as a concrete Pixel <see cref="GridLength"/> (the same Auto→Pixel conversion
    /// FolderPanelResizeTests.cs already proves for column 0). Reading that Pixel value BEFORE resetting
    /// to Auto — rather than reading the panel's rendered Bounds.Width, which would race the IsVisible
    /// binding update fired off the same PropertyChanged notification — reads the user's last dragged
    /// width deterministically, independent of view-binding timing.
    ///
    /// Showing the panel ALWAYS assigns a concrete <see cref="AiPanelDefaultColumnWidth"/>-or-remembered
    /// Pixel width — it deliberately does NOT fall back to <see cref="GridLength.Auto"/> the way the
    /// folder column does, and AiPanel (MainWindow.axaml) deliberately carries NO MinWidth either. Measured
    /// empirically: unlike the folder tree's narrow TreeView content, the real AI panel's content
    /// (transcript, cap meters, tabs, prompt box, …) naturally desires roughly 550px on its own, so a bare
    /// "Auto" column would settle wider than the intended 300px default — and a MinWidth floor wouldn't
    /// fix that (a floor can't cap a child that already wants MORE than the floor; a reviewer verified a
    /// MinWidth="300" attribute here is dead code — removing it left every test bit-for-bit identical).
    /// Always assigning an explicit Pixel width when shown is what actually produces the 300px default.
    /// </summary>
    private void SyncAiPanelColumnWidth(bool isAiPanelVisible)
    {
        if (this.FindControl<GridSplitter>("AiPanelSplitter")?.Parent is not Grid grid)
            return;

        ColumnDefinition column = grid.ColumnDefinitions[4];

        if (!isAiPanelVisible)
        {
            if (column.Width.GridUnitType == GridUnitType.Pixel)
                _aiPanelLastWidth = column.Width.Value;
            column.Width = GridLength.Auto;
            return;
        }

        column.Width = new GridLength(_aiPanelLastWidth ?? AiPanelDefaultColumnWidth, GridUnitType.Pixel);
    }

    private void WireFindReplace(FindReplaceViewModel findReplace)
    {
        if (ReferenceEquals(_findReplace, findReplace))
            return;

        if (_findReplace is not null)
        {
            _findReplace.NavigateRequested -= OnFindNavigate;
            _findReplace.PropertyChanged -= OnFindReplacePropertyChanged;
        }
        _findReplace = findReplace;
        _findReplace.NavigateRequested += OnFindNavigate;
        _findReplace.PropertyChanged += OnFindReplacePropertyChanged;
    }

    private void OnFindNavigate(FindMatch? match)
    {
        var editor = this.FindControl<EditorView>("EditorSurface");
        if (editor is null)
            return;
        if (match is { } m)
            editor.SelectRange(m.Index, m.Length);
        else
            editor.SelectRange(0, 0); // no match → clear the highlight.
    }

    private void OnFindReplacePropertyChanged(object? sender, PropertyChangedEventArgs e)
    {
        if (e.PropertyName == nameof(FindReplaceViewModel.IsVisible)
            && _findReplace is { IsVisible: true }
            && this.FindControl<FindReplaceView>("FindReplacePanel") is { } panel)
        {
            panel.FocusFind();
        }
    }

    // ----- Tab strip: tap-to-activate + drag-reorder (M8.1 / FR-1, cut-tail #1). -----
    //
    // Mirrors the ChecklistView drag pattern: PointerPressed records a drag/activation CANDIDATE; once the
    // pointer crosses DragStartThresholdPixels, OnWindowPointerMoved promotes it to a real DragDrop.DoDragDrop
    // carrying the tab's id, and the bubbling Drop resolves the horizontal gap → MainWindowViewModel.MoveTab
    // (ObservableCollection.Move with a same-slot no-op guard). A plain pointer tap (press+release with no
    // threshold-crossing movement in between) never starts a drag, so OnWindowPointerReleased activates the
    // candidate tab directly. Activation on drop: the dropped tab becomes the active tab (OnTabDrop).
    //
    // QA3-14 / QA3-3 (first fix, superseded in part): the OLD code called DragDrop.DoDragDrop unconditionally
    // on every PointerPressed, capturing the pointer for the OS drag loop on every press — including a plain
    // click. Deferring the drag start until a real threshold-crossing move (this file's PointerPressed/
    // PointerMoved candidate machinery) fixed THAT bug and remains correct — it's why a stationary click no
    // longer starts a drag at all.
    //
    // QA3-14 REOPENED (real-WM only, 2026-07-09): the deferred-drag fix alone was not sufficient. Activation
    // used to be wired to Avalonia's built-in Tapped gesture (Border Tapped="OnTabTapped" in the .axaml).
    // Decompiling Avalonia.Base 11.3.6's Avalonia.Input.Gestures confirms Tapped requires the raw hit-test
    // SOURCE of PointerPressed and PointerReleased to be the *same Interactive instance*
    // (`GetCaptured(ev) == e.Pointer.Captured ?? e.Source`; PointerReleased only raises Tapped when
    // `target == captured`). The chip's DataTemplate nests a TextBlock (the tab's display name) and a close
    // Button inside the Border. Avalonia's compositor hit-tests a TextBlock only where it actually painted
    // glyph ink (Avalonia.Rendering.Composition.Drawing.Nodes.RenderDataGlyphRunNode.HitTest checks the
    // shaped glyph run's own ink bounds, not the TextBlock's full layout Bounds), and the StackPanel wrapper
    // paints nothing (no Background) so it is never hit-tested at all — a miss there falls through to
    // whatever is underneath (this Border, since its Background is always a real, if Transparent, brush).
    // A press and a release that land a couple of pixels apart — ordinary real-mouse settle, not a drag —
    // can therefore resolve to genuinely DIFFERENT raw hit-test elements (e.g. the TextBlock's glyph ink for
    // the press vs. the Border's own background for the release, or vice versa) even though the user made
    // one stationary click. When that happens Gestures silently drops Tapped and the click does nothing.
    // Only a click deep enough inside one hit-testable region to absorb ordinary jitter (empirically, near
    // the chip's visual center) reliably lands on the SAME element both times.
    //
    // This is invisible under Avalonia.Headless: its headless-drawing test platform never paints real glyph
    // geometry, so a TextBlock never produces a hit-testable draw node there — every click on a chip resolves
    // to the same element (the Border) on both press and release regardless of position, so Tapped always
    // fired in the test suite even before this fix (confirmed empirically — a deliberately constructed
    // press-in-the-StackPanel-gap / release-on-the-close-Button headless probe, which SHOULD force differing
    // raw hit-test sources by the mechanism above, still activated correctly under the OLD Tapped-based code;
    // headless's simulated pointer gesture does not reproduce the source-identity split a real compositor
    // click can hit). That is exactly why the deferred-drag fix passed every headless test but did not fix
    // The maintainer's real-desktop symptom, and why this second fix is real-WM-only to verify.
    //
    // Fix: stop depending on hit-test SOURCE identity for activation. OnTabPointerPressed already records
    // the candidate at the Border level regardless of which descendant was actually hit (its `sender` is
    // always the Border — the handler is attached directly to it in .axaml, not resolved via bubbling hit-
    // test identity). OnWindowPointerReleased now activates that candidate directly, gated only on the
    // physical IPointer matching (immune to which descendant visual the release hit-tested to) and on the
    // drag threshold never having been crossed. A stationary press+release is therefore ALWAYS a plain click
    // over the tab's entire visible area, on a real WM as well as headless.

    /// <summary>
    /// Double-tap a folder-tree row (QA3-2 — the recommended minimum-viable interaction): a FILE row opens
    /// into a new tab via <see cref="MainWindowViewModel.OpenFolderTreeItemCommand"/>. A directory row is
    /// a no-op here — expand/collapse is the TreeViewItem.IsExpanded style binding, not this handler. The
    /// "Loading…" placeholder row is also excluded (QA3-2 REVISE) — the command guards it too, but this
    /// avoids even invoking it for a row that carries an empty FullPath.
    /// </summary>
    private void OnFolderTreeNodeDoubleTapped(object? sender, TappedEventArgs e)
    {
        if (sender is Border row && row.Tag is FolderTreeNode { IsDirectory: false, IsPlaceholder: false } node
            && DataContext is MainWindowViewModel shell)
        {
            shell.OpenFolderTreeItemCommand.Execute(node);
        }
    }

    /// <summary>
    /// Pointer press: record a drag/activation CANDIDATE — do NOT start the OS drag loop yet, and do NOT
    /// activate yet either. The candidate is promoted to a real <c>DragDrop.DoDragDrop</c> by
    /// <see cref="OnWindowPointerMoved"/> only once the pointer crosses <see cref="DragStartThresholdPixels"/>
    /// before release; a stationary press+release instead activates via <see cref="OnWindowPointerReleased"/>
    /// (see its doc comment — activation deliberately does NOT depend on Avalonia's built-in Tapped gesture,
    /// which is unreliable here on a real window manager; see the file-header comment for the full root
    /// cause).
    ///
    /// We do NOT call ActivateTab here either way — doing so before a drag starts would flash the content
    /// surface when dragging a background tab, because the editor surface would switch before the user's
    /// finger/mouse settles.
    ///
    /// QA2-7: PointerPressed is wired on the WHOLE chip Border (not a narrow drag-handle sliver — that was
    /// undiscoverable to a real user and regressed M8.1). To keep the × close Button working, a press whose
    /// original source is the Button (or any of its descendants, e.g. its text) is ignored here so the
    /// click reaches the Button's own Command instead of starting a drag candidate.
    /// </summary>
    private void OnTabPointerPressed(object? sender, PointerPressedEventArgs e)
    {
        if (sender is not Border chip || chip.Tag is not DocumentTab tab)
            return;
        if (DataContext is not MainWindowViewModel)
            return;
        if (!e.GetCurrentPoint(chip).Properties.IsLeftButtonPressed)
            return;
        if (!ShouldStartDrag(e.Source as Visual))
            return;

        _dragCandidateTab = tab;
        _dragCandidatePointer = e.Pointer;
        _dragCandidateStartPoint = e.GetPosition(this);
    }

    /// <summary>
    /// QA2-7: whether a pointer press on the tab chip should start the drag-reorder gesture, extracted as a
    /// pure predicate so the regression (the whole chip must be a drag source, not just a narrow sliver) is
    /// unit-testable without a live OS drag loop. Returns false when the press originated on the × close
    /// Button (or any of its descendants) so the Button's own Command still fires instead of a drag.
    /// </summary>
    internal static bool ShouldStartDrag(Visual? pressSource) =>
        pressSource is null || pressSource.FindAncestorOfType<Button>(includeSelf: true) is null;

    /// <summary>
    /// Window-level pointer move: promotes a pending drag CANDIDATE (<see cref="_dragCandidateTab"/>) to a
    /// real OS drag once the pointer travels past <see cref="DragStartThresholdPixels"/> from its press
    /// point (QA3-14 / QA3-3). Wired at the Window (not the tab chip) because a real drag gesture routinely
    /// carries the pointer off the chip's own bounds before the threshold is reached.
    /// </summary>
    private async void OnWindowPointerMoved(object? sender, PointerEventArgs e)
    {
        if (_dragCandidateTab is not { } tab || !ReferenceEquals(e.Pointer, _dragCandidatePointer))
            return;
        if (!e.GetCurrentPoint(this).Properties.IsLeftButtonPressed)
        {
            ClearDragCandidate();
            return;
        }
        if (!ExceedsDragThreshold(_dragCandidateStartPoint, e.GetPosition(this), DragStartThresholdPixels))
            return;

        ClearDragCandidate(); // starts at most once; clear before the await so re-entrant Moved events can't retrigger.

        var data = new DataObject();
        data.Set(DragTabIdFormat, tab.TabId);

        // UI-boundary: swallow any OS-level drag failure (network drive gone, compositor crash) so it cannot
        // propagate uncaught on the UI thread. OperationCanceledException (user pressed Escape) is a normal
        // completion — let it propagate so the caller's ambient token isn't masked.
        try
        {
            await DragDrop.DoDragDrop(e, data, DragDropEffects.Move);
        }
        catch (OperationCanceledException)
        {
            throw;
        }
        catch (Exception)
        {
            // OS drag failure — swallowed at the UI boundary (house "catch only at boundaries" rule).
        }
    }

    /// <summary>
    /// Window-level pointer release: activates the pending candidate tab directly (QA3-14 REOPENED fix — see
    /// the tab-strip file-header comment above <see cref="OnTabPointerPressed"/> for the full root cause: the
    /// built-in Tapped gesture's identity check is unreliable on a real window manager). Gated only on the
    /// SAME physical pointer that pressed the chip (never on which descendant visual the release happened to
    /// hit-test to) — a candidate only exists here when the press did not originate on the × close Button
    /// (<see cref="ShouldStartDrag"/>) and the pointer never crossed the drag threshold
    /// (<see cref="OnWindowPointerMoved"/> would already have cleared the candidate otherwise), so this is
    /// exactly "a plain click on the chip, wherever it fell."
    /// </summary>
    private void OnWindowPointerReleased(object? sender, PointerReleasedEventArgs e)
    {
        if (!ReferenceEquals(e.Pointer, _dragCandidatePointer))
            return;

        if (_dragCandidateTab is { } tab && DataContext is MainWindowViewModel shell)
            shell.ActivateTab(tab);

        ClearDragCandidate();
    }

    private void OnWindowPointerCaptureLost(object? sender, PointerCaptureLostEventArgs e)
    {
        if (ReferenceEquals(e.Pointer, _dragCandidatePointer))
            ClearDragCandidate();
    }

    private void ClearDragCandidate()
    {
        _dragCandidateTab = null;
        _dragCandidatePointer = null;
        _dragCandidateStartPoint = default;
    }

    /// <summary>
    /// Test-only observability seam (QA3-14 coverage): whether a drag candidate is currently pending
    /// promotion. Read-only — adds no behavior and changes no timing; <see cref="OnWindowPointerMoved"/>'s
    /// candidate-clear-before-await already happens exactly as before. Exists because the real
    /// <c>DragDrop.DoDragDrop</c> the promotion leads into never resolves under the headless test platform
    /// (confirmed empirically: it neither completes nor throws within several seconds), so a test cannot
    /// await its way to an assertion — this lets it observe the synchronous promotion DECISION instead.
    /// </summary>
    internal bool HasPendingDragCandidate => _dragCandidateTab is not null;

    /// <summary>
    /// Pure predicate (QA3-14 / QA3-3 regression guard): whether <paramref name="current"/> has traveled far
    /// enough from <paramref name="start"/> to promote a pending tab-chip press into an OS drag. Extracted so
    /// the threshold decision is unit-testable without a live pointer or OS drag loop.
    /// </summary>
    internal static bool ExceedsDragThreshold(Point start, Point current, double thresholdPixels)
    {
        double dx = current.X - start.X;
        double dy = current.Y - start.Y;
        return (dx * dx) + (dy * dy) >= thresholdPixels * thresholdPixels;
    }

    private void OnTabDragOver(object? sender, DragEventArgs e) =>
        e.DragEffects = e.Data.Contains(DragTabIdFormat) ? DragDropEffects.Move : DragDropEffects.None;

    private void OnTabDrop(object? sender, DragEventArgs e)
    {
        if (DataContext is not MainWindowViewModel shell)
            return;
        if (e.Data.Get(DragTabIdFormat) is not string draggedId)
            return;

        var strip = this.FindControl<ItemsControl>("TabStrip");
        if (strip is null)
            return;

        DocumentTab? dragged = shell.Tabs.FirstOrDefault(t => t.TabId == draggedId);
        if (dragged is null)
            return;

        // Collect realized container widths (with spacing) and resolve the target index.
        var widths = new List<double>(strip.ItemCount);
        for (int i = 0; i < strip.ItemCount; i++)
        {
            double w = (strip.ContainerFromIndex(i) as Control)?.Bounds.Width ?? 80;
            widths.Add(w);
        }

        int targetIndex = ComputeDropIndex(widths, TabStripSpacing, e.GetPosition(strip).X);
        shell.MoveTab(dragged, targetIndex);
        shell.ActivateTab(dragged); // the dropped tab becomes the active one.
        e.Handled = true;
    }

